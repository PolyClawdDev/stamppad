/* ---------- ZIP-244 vectors ---------- */

export interface Zip244Vector {
  tx: string;
  /** Internal byte order, as the digest comes out. Reverse for display. */
  txid: string;
  auth_digest: string;
  amounts: number[];
  script_pubkeys: string[];
  transparent_input: number | null;
  sighash_shielded: string | null;
  sighash_all: string | null;
  sighash_none: string | null;
  sighash_single: string | null;
  sighash_all_anyone: string | null;
  sighash_none_anyone: string | null;
  sighash_single_anyone: string | null;
}

/**
 * The ZIP's own vectors, from zcash/zcash-test-vectors. The file is a header
 * row naming the columns followed by one array per transaction.
 */
export function zip244Vectors(): Zip244Vector[] {
  const rows = vectorFixture as unknown[];
  const names = (rows[1] as string[])[0]!.split(", ");
  return (rows.slice(2) as unknown[][]).map((row) => {
    const record: Record<string, unknown> = {};
    names.forEach((name, index) => (record[name] = row[index]));
    return record as unknown as Zip244Vector;
  });
}

